// Neutral journal export (docs/ACCOUNTING.md → Goal): one row per line, any accountant can import or key it.
import ExcelJS from 'exceljs';
import type { JournalEntry, trialBalance } from './journal.js';

const MONEY = '#,##0.00';
const HEADER_FILL: ExcelJS.Fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: 'FFE2E8F0' } };

const excelDate = (v: string) => {
  const m = /^(\d{4})-(\d{2})-(\d{2})/.exec(v);
  return m ? new Date(Date.UTC(Number(m[1]), Number(m[2]) - 1, Number(m[3]))) : null;
};

function header(ws: ExcelJS.Worksheet, rowNo: number, labels: string[]) {
  const row = ws.getRow(rowNo);
  row.values = labels;
  row.font = { bold: true };
  row.eachCell((c) => { c.fill = HEADER_FILL; });
  ws.views = [{ state: 'frozen', ySplit: rowNo }];
}

export function journalWorkbook(
  entries: (JournalEntry & { entry_no: string })[],
  tb: ReturnType<typeof trialBalance>,
  orgName: string,
  month: string,
) {
  const book = new ExcelJS.Workbook();
  book.creator = 'DocFlow AI';
  book.created = new Date();

  // Sheet 1: journal lines (long format)
  const ws = book.addWorksheet('Journal', { pageSetup: { orientation: 'landscape', fitToPage: true, fitToWidth: 1, fitToHeight: 0 } });
  ws.getCell('A1').value = `สมุดรายวันทั่วไป / General journal · ${orgName} · ${month}`;
  ws.getCell('A1').font = { bold: true, size: 14 };
  ws.getCell('A2').value = 'Generated by DocFlow AI from confirmed and approved receipts. Management journal; review before filing.';
  ws.getCell('A2').font = { size: 10, color: { argb: 'FF475569' } };
  const labels = ['Date', 'Entry no.', 'Document no.', 'Account code', 'Account name', 'Debit', 'Credit', 'Property', 'Vendor', 'Tax ID', 'Description', 'Line memo'];
  header(ws, 4, labels);
  ws.columns = [12, 16, 16, 12, 32, 14, 14, 20, 26, 16, 30, 30].map((width) => ({ width }));

  let r = 5;
  for (const e of entries) {
    for (const l of e.lines) {
      const row = ws.getRow(r++);
      row.values = [excelDate(e.date), e.entry_no, e.document_no, l.account_code, l.account_name, l.debit || null, l.credit || null,
        orgName, e.vendor_name, e.vendor_taxid, e.description, l.memo];
      row.getCell(1).numFmt = 'dd/mm/yyyy';
      row.getCell(6).numFmt = MONEY;
      row.getCell(7).numFmt = MONEY;
      row.getCell(4).numFmt = '@';
      row.getCell(10).numFmt = '@';
    }
  }
  const last = r - 1;
  const total = ws.getRow(r);
  total.getCell(5).value = 'Total';
  total.font = { bold: true };
  for (const [col, key] of [['F', 'debit'], ['G', 'credit']] as const) {
    const sum = Math.round(entries.flatMap((e) => e.lines).reduce((t, l) => t + l[key], 0) * 100) / 100;
    total.getCell(col).value = { formula: last >= 5 ? `SUM(${col}5:${col}${last})` : '0', result: sum };
    total.getCell(col).numFmt = MONEY;
  }
  if (last >= 5) ws.autoFilter = { from: { row: 4, column: 1 }, to: { row: last, column: labels.length } };

  // Sheet 2: movement per account this month
  const tbs = book.addWorksheet('Trial balance');
  tbs.getCell('A1').value = `Trial balance movement · ${orgName} · ${month}`;
  tbs.getCell('A1').font = { bold: true, size: 14 };
  header(tbs, 3, ['Account code', 'Account name', 'Debit', 'Credit', 'Net (Dr − Cr)']);
  tbs.columns = [14, 36, 16, 16, 16].map((width) => ({ width }));
  tb.forEach((x, i) => {
    const row = tbs.getRow(i + 4);
    row.values = [x.account_code, x.account_name, x.debit, x.credit, Math.round((x.debit - x.credit) * 100) / 100];
    row.getCell(1).numFmt = '@';
    [3, 4, 5].forEach((c) => { row.getCell(c).numFmt = MONEY; });
  });
  return book;
}
